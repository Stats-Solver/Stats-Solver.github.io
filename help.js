$("#links").show(); $("#topics").hide();
$("#usefullinks").hide(); $("#listtopics").show();

function switchlinks() {
    $("#links").hide(); $("#topics").show();
    $("#usefullinks").show(); $("#listtopics").hide();
}
 
function switchtopics() {
    $("#links").show(); $("#topics").hide();
    $("#usefullinks").hide(); $("#listtopics").show();
}