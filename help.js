$("#listtopics").show(); $("#usefullinks").hide();
 
function switchlinks() {
    $("#topics").show(); $("#links").hide();
    $("#listtopics").hide(); $("#usefullinks").show();
}

function switchtopics() {
    $("#topics").hide(); $("#links").show(); 
    $("#listtopics").show(); $("#usefullinks").hide();
}